#!/usr/bin/env bash
# mk-fips-config.sh — idempotent FIPS config generator for a CDN region node.
#
# Renders fips.yaml from environment. Never writes a key to disk from here:
# the nsec is read from the environment (or a credentials file path) and the
# rendered config is written with 0600. See docs/RUNBOOK.md.
#
# Usage:
#   FIPS_NSEC=nsec1... REGION=us PUBLIC_IP=1.2.3.4 ./mk-fips-config.sh /tmp/fips.yaml
#
# Idempotence: running twice with the same inputs yields a byte-identical file.
# Verified by tests/test-mk-fips-config.sh.

set -euo pipefail

OUT="${1:-/etc/fips/fips.yaml}"
REGION="${REGION:-unknown}"
TUN_MTU="${FIPS_TUN_MTU:-1280}"
UDP_BIND="${FIPS_UDP_BIND:-0.0.0.0:2121}"
TCP_BIND="${FIPS_TCP_BIND:-0.0.0.0:8443}"
PUBLIC_IP="${PUBLIC_IP:-}"

# Identity: prefer a credentials file (systemd LoadCredential), else env.
NSEC=""
if [ -n "${CREDENTIALS_DIRECTORY:-}" ] && [ -f "${CREDENTIALS_DIRECTORY}/fips-nsec" ]; then
  NSEC="$(cat "${CREDENTIALS_DIRECTORY}/fips-nsec")"
elif [ -n "${FIPS_NSEC_FILE:-}" ] && [ -f "${FIPS_NSEC_FILE}" ]; then
  NSEC="$(cat "${FIPS_NSEC_FILE}")"
elif [ -n "${FIPS_NSEC:-}" ]; then
  NSEC="${FIPS_NSEC}"
fi

if [ -z "$NSEC" ]; then
  echo "mk-fips-config: no identity supplied (FIPS_NSEC, FIPS_NSEC_FILE, or LoadCredential)" >&2
  exit 1
fi

# Validate the key shape without echoing it.
case "$NSEC" in
  nsec1*) : ;;
  *) echo "mk-fips-config: identity is not an nsec1... bech32 string" >&2; exit 1 ;;
esac

# external_addr is REQUIRED for the TCP transport when advertising on nostr;
# without it FIPS warns every second and the TCP endpoint is invisible.
TCP_EXT=""
if [ -n "$PUBLIC_IP" ]; then
  TCP_EXT=$'\n    external_addr: "'"${PUBLIC_IP}:${TCP_BIND##*:}"'"'
fi

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

# NOTE: keys are emitted to a temp file with restrictive perms and moved into
# place atomically. We deliberately never `set -x` in this script.
umask 077
cat > "$TMP" <<YAML
# Generated by mk-fips-config.sh — region: ${REGION}
# Do not edit by hand; re-run the generator. Idempotent.
node:
  identity:
    nsec: "${NSEC}"
  discovery:
    nostr:
      enabled: true
      policy: configured_only
      app: "fips-overlay-v1"
      advertise: false

tun:
  enabled: true
  name: fips0
  mtu: ${TUN_MTU}

dns:
  enabled: true
  bind_addr: "127.0.0.1"

transports:
  udp:
    bind_addr: "${UDP_BIND}"
    advertise_on_nostr: true
  tcp:
    bind_addr: "${TCP_BIND}"${TCP_EXT}
    advertise_on_nostr: true

peers: []
YAML

install -m 600 "$TMP" "$OUT"

# Assert exactly one peers: key (a duplicate makes FIPS crash-loop).
n=$(grep -c '^peers:' "$OUT")
if [ "$n" != "1" ]; then
  echo "mk-fips-config: expected exactly 1 'peers:' key, found $n" >&2
  exit 1
fi

echo "wrote $OUT (region=${REGION}, tcp_external=${TCP_EXT:1:20}...)"
